#!/usr/bin/env python3
"""
convert_rules.py - the CI convert stage.

Turns each Sigma rule into deployable artifacts and writes them under
build/converted/:
  - <name>.lucene   : an Elasticsearch/Lucene query (via pySigma's maintained backend)
  - wazuh_local_rules.xml : a single Wazuh ruleset the lab SIEM can load

Why two targets
---------------
Sigma is the portable source of truth. The Lucene output proves the rules convert
cleanly with a maintained pySigma backend (a good spec-conformance signal). The
Wazuh XML is what my actual home-lab SIEM ingests - there is no maintained pySigma
Wazuh backend, so this module emits a documented, deliberately simple XML mapping
of each rule's selection fields. It mirrors the hand-written rules already deployed
in my detection-engineering repo (ids 100010+). It is an approximation, not a
1:1 compiler - complex correlation (count()) is emitted as a commented TODO for a
human to wire to a Wazuh <frequency> rule.

On merge to main the CI publishes build/converted/ as an artifact; the docs
describe how that artifact would be pushed to a live Wazuh manager.
"""
from __future__ import annotations

import sys
from pathlib import Path
from xml.sax.saxutils import escape

sys.path.insert(0, str(Path(__file__).resolve().parent))

import yaml  # noqa: E402
from rule_loader import REPO_ROOT, discover_rules  # noqa: E402

from sigma.collection import SigmaCollection  # noqa: E402
from sigma.backends.elasticsearch import LuceneBackend  # noqa: E402

OUT_DIR = REPO_ROOT / "build" / "converted"
WAZUH_BASE_ID = 100200  # a fresh block, distinct from the hand-written 100010+ rules


def _is_correlation(doc: dict) -> bool:
    return "count()" in str(doc.get("detection", {}).get("condition", ""))


def to_lucene(raw: str, doc: dict) -> str:
    # A windowed count() correlation cannot be expressed as a single Lucene query.
    # Emit the base-selection query with a note rather than failing the pipeline.
    if _is_correlation(doc):
        stripped = dict(doc)
        det = dict(doc["detection"])
        det["condition"] = "selection"  # convert only the base filter
        stripped["detection"] = det
        base_query = "\n".join(LuceneBackend().convert(SigmaCollection.from_dicts([stripped])))
        return (
            "// NOTE: correlation rule (windowed count()). Lucene cannot express the\n"
            "// threshold; below is the BASE selection only. Apply the count()>N window\n"
            "// in the SIEM (Wazuh <frequency>, Elastic threshold rule, etc.).\n"
            f"{base_query}"
        )
    return "\n".join(LuceneBackend().convert(SigmaCollection.from_yaml(raw)))


def _wazuh_level(sigma_level: str) -> int:
    return {"informational": 3, "low": 5, "medium": 8, "high": 12, "critical": 14}.get(
        sigma_level, 8
    )


def to_wazuh(doc: dict, rule_id: int) -> str:
    """Emit one <rule> block approximating the Sigma selection for Wazuh."""
    title = doc.get("title", "untitled")
    level = _wazuh_level(doc.get("level", "medium"))
    detection = doc.get("detection", {})
    tags = [t for t in (doc.get("tags") or []) if str(t).startswith("attack.t")]
    mitre_id = tags[0].split(".", 1)[1].upper() if tags else ""

    lines = [f'  <rule id="{rule_id}" level="{level}">']
    # Match on the primary selection's fields as <field> regex tests.
    selection = detection.get("selection")
    if isinstance(selection, dict):
        for key, val in selection.items():
            field_name = key.split("|", 1)[0]
            values = val if isinstance(val, list) else [val]
            pattern = "|".join(escape(str(v)) for v in values)
            lines.append(f'    <field name="{escape(field_name)}">{pattern}</field>')
    else:
        lines.append("    <!-- non-trivial selection; review mapping by hand -->")

    if "count()" in str(detection.get("condition", "")):
        lines.append(
            "    <!-- TODO: correlation rule - wire to a Wazuh <frequency>/<timeframe> "
            "rule by hand; field matching alone will over-fire -->"
        )

    lines.append(f"    <description>{escape(title)}</description>")
    if mitre_id:
        lines.append("    <mitre>")
        lines.append(f"      <id>{escape(mitre_id)}</id>")
        lines.append("    </mitre>")
    lines.append("  </rule>")
    return "\n".join(lines)


def main() -> int:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    rules = discover_rules()
    if not rules:
        print("No rules to convert.")
        return 1

    wazuh_rules = [
        '<!-- AUTO-GENERATED by convert_rules.py from Sigma sources. Do not edit by hand. -->',
        '<group name="detection-as-code,sigma-generated,">',
    ]
    for i, path in enumerate(rules):
        raw = path.read_text(encoding="utf-8")
        doc = yaml.safe_load(raw)

        lucene = to_lucene(raw, doc)
        (OUT_DIR / f"{path.stem}.lucene").write_text(lucene + "\n", encoding="utf-8")

        wazuh_rules.append("")
        wazuh_rules.append(f"  <!-- {path.relative_to(REPO_ROOT)} -->")
        wazuh_rules.append(to_wazuh(doc, WAZUH_BASE_ID + i))
        print(f"converted  {path.stem}  -> lucene + wazuh")

    wazuh_rules.append("</group>")
    (OUT_DIR / "wazuh_local_rules.xml").write_text("\n".join(wazuh_rules) + "\n", encoding="utf-8")

    print("-" * 60)
    print(f"Wrote {len(rules)} lucene queries + wazuh_local_rules.xml to {OUT_DIR}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
